export type KnownMethod = typeof knownMethods[number];

const byLowerCase = new Map<string, KnownMethod>(
  knownMethods.map((name) => [name.toLowerCase(), name]),
);

/** Bot API method names are case-insensitive. */
export function knownMethod(name: string): KnownMethod | undefined {
  return byLowerCase.get(name.toLowerCase());
}
